import type { BowlModel, BowlParams, MeshArrays } from "../geometry/types";

function polyhedron(mesh: MeshArrays | undefined): string {
  if (!mesh) return "union() {}";
  const points = Array.from({length:mesh.positions.length/3}, (_,i) => Array.from(mesh.positions.slice(i*3,i*3+3),n=>Number(n.toFixed(5))));
  const faces = Array.from({length:mesh.indices.length/3},(_,i)=>Array.from(mesh.indices.slice(i*3,i*3+3)).reverse());
  return `polyhedron(points=${JSON.stringify(points)}, faces=${JSON.stringify(faces)}, convexity=12);`;
}

/** Editable CAD solids; decoration outlines come from the selected font, not an imported STL. */
export function modelToScad(params: BowlParams, model: BowlModel): string {
  const number = (n: number) => Number(n.toFixed(5));
  return `// MONO - OpenSCAD parametric pet bowl. Millimetres.
// Original geometry, no imported STL or source logo.
// Name/icon outlines generated by the app from the selected font.
// Change the name in the app and export again to refresh these outlines.
part = "assembly"; // [assembly,body,base,text]
body_d = ${number(params.bodyDiameter)};
body_h = ${number(params.height)};
wall = ${number(params.wallThickness)};
bottom = ${number(params.bottomThickness)};
mouth_shrink = ${number(params.mouthShrink)};
tray_d = ${number(params.trayDiameter)};
tray_h = ${number(params.trayHeight)};
stand_h = ${number(params.islandHeight)};
tilt = ${number(params.tiltDeg)};
rim = ${number(params.rimRadius)};
clearance = ${number(params.fitClearance)};
insert_lip = ${number(params.insertLipDiameter)};
insert_mouth = ${number(params.insertMouthDiameter)};
insert_clearance = ${number(params.insertClearance)};
moat = ${params.moatEnabled};
moat_width = ${number(params.moatWidth)};
moat_depth = ${number(params.moatDepth)};
moat_gap = ${number(params.moatGap)};
windows = ${params.windowEnabled};
texture = "${params.baseTexture}"; // [smooth,ribs,twist]
ribs = ${Math.round(params.ribCount)};
engrave = ${params.textStyle === "engrave"};
$fn = 128;
s = insert_lip/130;
br = body_d/2;
mr = max(insert_lip/2+wall+1,br-mouth_shrink);
fh = br*0.772;
lh = max(2.4,bottom);
seat = insert_mouth/2+0.7+insert_clearance;
f = min(rim,wall,(mr-seat)/3);
tr = tray_d/2;
rz = tray_h*36.8/60;
lift = rz+6*s+clearance;
peak = max(lift+4,rz+stand_h);
support = min(fh+3*s,tr-wall-4);
floor_z = max(bottom+1,rz-(moat ? moat_depth : 0));
body_profile = [[fh,0],[br-f,0],[br,f],[mr,body_h-f],[mr-f,body_h],
 [seat,body_h],[seat,body_h-lh],[mr-wall,body_h-lh],[br-wall,lh],[fh,lh]];
base_profile = [[0,peak],[min(53.4*s,fh-4),peak],[fh-clearance,lift+lh],
 [fh-clearance,lift],[support,lift],[support,rz],[tr-f,rz],[tr,rz-f],
 [tr,f],[tr-f,0],[tr-wall,0],[tr-wall,floor_z-bottom],[0,floor_z-bottom]];
function blend(z) = let(t=min(1,max(0,(z*102.8571395874/body_h-38)/(100.1-38)))) t*t*(3-2*t);
function vertex(p,a) = [p[0]*cos(a),p[0]*sin(a),lift+p[1]+blend(p[1])*p[0]*sin(a)*tan(tilt)];
module tilted_shell() {
 profile=[for(i=[0:len(body_profile)-1]) if(i==0 || norm(body_profile[i]-body_profile[i-1])>0.00001) body_profile[i]];
 n=128; k=len(profile);
 points=[for(p=profile,a=[0:n-1]) vertex(p,a*360/n)];
 faces=[for(i=[0:k-1],j=[0:n-1]) each [
 [i*n+j,i*n+(j+1)%n,((i+1)%k)*n+(j+1)%n],
 [i*n+j,((i+1)%k)*n+(j+1)%n,((i+1)%k)*n+j]]];
 polyhedron(points=points,faces=[for(face=faces) [face[2],face[1],face[0]]],convexity=12);
}
module decoration() { ${polyhedron(model.parts.find(p=>p.name==="text")?.mesh)} }
module body() { difference() {
 tilted_shell();
 if(windows) translate([0,0,lift+body_h*0.77]) rotate([0,90,0])
  scale([1.8,1,1]) cylinder(h=220*s,r=7.5*s,center=true,$fn=64);
 if(engrave) decoration();
} }
module groove() {
 translate([0,0,1]) linear_extrude(height=max(1,rz-2),twist=texture=="twist" ? 12 : 0,slices=18)
  translate([tr-0.55,-0.6]) square([1.55,1.2]);
}
module base() { difference() {
 rotate_extrude() polygon(base_profile);
 if(moat && min(support+moat_gap+moat_width,tr-wall-0.5)>support+moat_gap+1)
 translate([0,0,rz-moat_depth]) difference() {
  cylinder(h=moat_depth+1,r=min(support+moat_gap+moat_width,tr-wall-0.5));
  translate([0,0,-0.5]) cylinder(h=moat_depth+2,r=support+moat_gap);
 }
 if(texture!="smooth") for(a=[0:360/ribs:359.999]) rotate([0,0,a]) groove();
} }
if(part=="assembly" || part=="body") color("Ivory") body();
if(part=="assembly" || part=="base") color("Peru") base();
if(part=="assembly" || part=="text") color("SaddleBrown") decoration();
`;
}
